fn criterion_benchmark(c: &mut Criterion) {
    c.bench_function("gen_prime u256", |b| b.iter(|| prime::new(256)));
    c.bench_function("gen_safe_prime u256", |b| b.iter(|| safe_prime::new(256)));

    let Ok(prime_512) = BigUint::from_str_radix(
        "1675975991242824637446753124775730765934920727574049172215445180465220503759193372100234287270862928461253982273310756356719235351493321243304213304923049",
        10,
    ) else {
        return;
    };
    c.bench_function("Baillie-PSW u512", |b| {
        b.iter(|| prime::strong_check(std::hint::black_box(&prime_512)))
    });

    let mut rng = StdRng::seed_from_u64(0x5eed);
    c.bench_function("Miller-Rabin u512", |b| {
        b.iter(|| prime::check_with(std::hint::black_box(&prime_512), &mut rng))
    });

    let composite_1024 = &prime_512 * &prime_512;
    c.bench_function("Baillie-PSW composite u1024", |b| {
        b.iter(|| prime::strong_check(std::hint::black_box(&composite_1024)))
    });

    let sieve_worst_case_512 = &prime_512 * 17_863_u32;
    c.bench_function("small-prime sieve u512", |b| {
        b.iter(|| prime::strong_check(std::hint::black_box(&sieve_worst_case_512)))
    });
}

fn large_prime_benchmarks(c: &mut Criterion) {
    if cfg!(debug_assertions) {
        return;
    }

    let Some(primes) = [MODP_1024, MODP_2048, MODP_4096, MODP_8192]
        .map(modp_prime)
        .into_iter()
        .collect::<Option<Vec<_>>>()
    else {
        return;
    };
    let mut group = c.benchmark_group("large prime checks");
    group.sample_size(10);

    for (bits, candidate) in [1024_u32, 2048, 4096, 8192].iter().zip(&primes) {
        group.bench_with_input(BenchmarkId::new("Baillie-PSW", bits), candidate, |b, n| {
            b.iter(|| prime::strong_check(std::hint::black_box(n)))
        });

        let mut rng = StdRng::seed_from_u64(0x5eed_u64 ^ u64::from(*bits));
        group.bench_with_input(BenchmarkId::new("Miller-Rabin", bits), candidate, |b, n| {
            b.iter(|| prime::check_with(std::hint::black_box(n), &mut rng))
        });

        let sieve_candidate = candidate * 17_863_u32;
        group.bench_with_input(
            BenchmarkId::new("Small-prime sieve", bits),
            &sieve_candidate,
            |b, n| b.iter(|| prime::strong_check(std::hint::black_box(n))),
        );
    }

    group.bench_function("Generate safe prime/1024", |b| {
        b.iter(|| {
            let mut rng = StdRng::seed_from_u64(0x5eed_1024);
            safe_prime::from_rng(1024, &mut rng)
        })
    });
    group.finish();
}

fn modp_prime(hex: &str) -> Option<BigUint> {
    BigUint::from_str_radix(hex, 16).ok()
}

